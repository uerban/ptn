//! Generated tuple corpus for the engine-owned RAPTOR regression suite.
//!
//! One entry per pinned query vector: which committed `.ptb` (and optional PTFT
//! `transfers.bin`) to route over, the query itself, and the hand-checked
//! expectations that must hold independently of the committed golden
//! (`golden/raptor-plan.golden.tsv`). Consumed by `raptor_behavior.rs`.
//!
//! Each expectation field is an EXPLICIT literal, not a recomputed value: a
//! behaviour change flips a pinned board/alight position, a pinned
//! board/alight second, or a pinned empty/non-empty verdict, and the suite
//! fails with the offending tuple named. The golden file additionally pins the
//! FULL projected itinerary list (every leg field, array order included) for
//! every tuple x PatternMode, so a change outside the pinned fields is caught
//! too.
//!
//! Cargo compiles every file under `tests/` as its own test target, so this
//! module is also built standalone with no `#[test]` fns — hence the
//! crate-level dead-code allowance (same posture as `tests/util.rs`).
#![allow(dead_code)]

/// One pinned query vector plus its hand-checked expectations.
pub struct Tuple {
    /// Stable label, used in failure messages and as the golden record key.
    pub name: &'static str,
    /// Repo-relative path to the committed `.ptb` both engines read.
    pub ptb: &'static str,
    /// Repo-relative path to the paired PTFT `transfers.bin`, when the fixture
    /// has one. `None` ⇒ footpath relaxation is skipped for this tuple.
    pub transfers: Option<&'static str>,
    /// `(stop_id, walk_secs)` entry/exit sets, ORDER SIGNIFICANT (the equal-
    /// `alight_secs` tie-break reads exit order).
    pub entry: &'static [(&'static str, u32)],
    pub exit: &'static [(&'static str, u32)],
    pub departure_secs: i64,
    /// `YYYYMMDD`; the engine resolves the active-service set from it.
    pub date: u32,
    pub max_rounds: Option<u32>,
    /// `"default"` | `"wheelchair"` | `"bicycle"`.
    pub mobility: &'static str,
    /// GTFS `route_type` integers (base OR extended); the engine normalises
    /// each to its Mode family and excludes the whole family.
    pub excluded_route_ids: &'static [&'static str],
    pub excluded_route_types: &'static [u16],
    /// Whether a non-empty itinerary list is expected. Under `Off` this is not
    /// asserted for `multi_pattern` tuples (their target stop is off the
    /// canonical stop-sequence, so the canonical-only scan cannot reach it).
    pub expect_non_empty: bool,
    /// The fixture carries stops off the canonical route stop-sequence.
    pub multi_pattern: bool,
    /// Run the tuple under the two ON modes only: no `PatternMode::Off` record
    /// in either golden. Carry-less current-v1 fixtures otherwise run under
    /// `Off` too — the flat path reads times and boarding through the band.
    pub band_only: bool,
    /// `(route_id, board_stop_idx, alight_stop_idx)` of the first transit leg.
    pub expect_first_leg: Option<(&'static str, u32, u32)>,
    /// Restricts `expect_first_leg` to these PatternModes. A folded short trip
    /// rides its covering pattern at an offset under `CoveringMerge`, so its
    /// positions differ from `Unbounded` and one golden cannot hold for both.
    pub expect_first_leg_modes: Option<&'static [&'static str]>,
    /// `(board_secs, alight_secs)` of the first itinerary — the independent
    /// pin on the overnight −86400 rewrite.
    pub expect_board_alight_secs: Option<(i64, i64)>,
    /// `(depart_secs, arrive_secs, approximate)` of the first transit leg.
    pub expect_first_transit_timing: Option<(i64, i64, bool)>,
}

