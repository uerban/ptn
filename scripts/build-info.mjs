// Build-info producer. Used by both:
//  - frontend (vite.config.ts imports `readBuildInfo` and feeds the
//    result through Vite's `define`)
//  - backend (CLI invocation from the package's `prebuild` hook writes
//    a generated TS module under packages/backend/src/generated/)
//
// Behaviour:
//  - version is the declared version from <packageDir>/package.json, verbatim
//  - commit precedence: GIT_SHA env build-arg (only when it's a hex SHA — a
//    non-hex value is rejected, not stamped) > local `git rev-parse` > "unknown"
//  - short SHA + "-dirty" if working copy has uncommitted changes (git path)
//  - commit falls back to "unknown" when git is unavailable / `.git/` is
//    missing — never fails a build
//
// GIT_SHA lets a container build stamp the deployed commit without a usable
// local `git` (e.g. CI's ${{ github.sha }}, or the Docker build resolving the
// Portainer-cloned .git via `git rev-parse` and exporting it). It is also the
// only clean path inside the image, where the partial working tree would make
// a bare `git status` spuriously read "-dirty".

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// git exports its repo-discovery variables into every hook it runs, and they
// take precedence over `cwd`. Inheriting them means that running this script
// from a hook (or any git-invoked context) reads whichever repository the hook
// belongs to rather than `cwd`, and stamps that repo's commit and dirty state
// into the generated build info.
//
// Only the discovery variables are dropped, never GIT_SHA — that is this
// repo's own build arg and takes precedence over the git walk by design.
const GIT_DISCOVERY_VARS = [
  "GIT_DIR",
  "GIT_COMMON_DIR",
  "GIT_WORK_TREE",
  "GIT_INDEX_FILE",
  "GIT_INDEX_VERSION",
  "GIT_OBJECT_DIRECTORY",
  "GIT_ALTERNATE_OBJECT_DIRECTORIES",
  "GIT_NAMESPACE",
  "GIT_PREFIX",
  "GIT_CEILING_DIRECTORIES",
];

function gitEnv() {
  return Object.fromEntries(
    Object.entries(process.env).filter(([key]) => !GIT_DISCOVERY_VARS.includes(key)),
  );
}

function tryGit(cwd, args) {
  try {
    return execFileSync("git", args, {
      cwd,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      env: gitEnv(),
    }).trim();
  } catch {
    return null;
  }
}

// Returns a normalized short SHA from the GIT_SHA env var, or null when it is
// absent / empty / "unknown" / not a hex commit SHA (so the caller falls
// through to local git, then to "unknown"). A full 40-char SHA (e.g.
// ${{ github.sha }}) is abbreviated to 8; an already-short hex SHA (7–39 chars)
// is passed through as-is. A value that is not a hex SHA — a typo'd build-arg,
// a branch/ref name like `refs/heads/main`, an over-long string — is rejected
// with a warning rather than stamped as a bogus, authoritative-looking commit.
// (Note the local-git path uses git's adaptive `--short` length, which can
// differ from 8 as the repo grows; both forms are valid commit prefixes.)
function shaFromEnv() {
  const raw = (process.env.GIT_SHA ?? "").trim();
  if (!raw || raw.toLowerCase() === "unknown") return null;
  if (/^[0-9a-f]{40}$/i.test(raw)) return raw.slice(0, 8); // full SHA → abbreviate
  if (/^[0-9a-f]{7,39}$/i.test(raw)) return raw; // already-short SHA → as-is
  process.stderr.write(
    `[build-info] GIT_SHA="${raw}" is not a hex commit SHA — ignoring it (check the build-arg); falling back to local git / "unknown"\n`,
  );
  return null;
}

export function readBuildInfo(packageDir) {
  const pkg = JSON.parse(readFileSync(resolve(packageDir, "package.json"), "utf8"));
  const version = String(pkg.version ?? "0.0.0");
  const builtAt = new Date().toISOString();

  const envSha = shaFromEnv();

  const gitSha = tryGit(packageDir, ["rev-parse", "--short", "HEAD"]);
  // `--untracked-files=no` keeps `pnpm install` byproducts (node_modules/,
  // build outputs) from polluting the dirty bit when the Docker build
  // runs the script with `.git/` copied into the install stage.
  const statusRaw = tryGit(packageDir, ["status", "--porcelain", "--untracked-files=no"]);
  const hasTrackedChanges = statusRaw !== null && statusRaw.trim().length > 0;

  // Commit precedence: explicit GIT_SHA (build-arg) wins; else local git;
  // else "unknown".
  let commit;
  if (envSha !== null) {
    commit = envSha;
  } else if (gitSha !== null) {
    commit = hasTrackedChanges ? `${gitSha}-dirty` : gitSha;
  } else {
    commit = "unknown";
  }

  if (commit === "unknown") {
    process.stderr.write("[build-info] no GIT_SHA and git unavailable / no .git — falling back\n");
  }

  return { version, commit, builtAt };
}

export function emitTsModule(info) {
  return [
    "// Auto-generated by scripts/build-info.mjs — do not edit.",
    'import type { BuildInfo } from "@pt/shared";',
    "",
    `export const buildInfo: BuildInfo = ${JSON.stringify(info, null, 2)};`,
    "",
  ].join("\n");
}

// CLI entry: node scripts/build-info.mjs <packageDir> <outputPath>
const isCli = process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isCli) {
  const [packageDir, outputPath] = process.argv.slice(2);
  if (!packageDir || !outputPath) {
    process.stderr.write("usage: build-info.mjs <packageDir> <outputPath>\n");
    process.exit(2);
  }
  const info = readBuildInfo(packageDir);
  const ts = emitTsModule(info);
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, ts);
  process.stderr.write(`[build-info] wrote ${outputPath} (version=${info.version}, commit=${info.commit})\n`);
}
